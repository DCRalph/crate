import { describe, expect, test } from "bun:test";

import { decodePlaylistFile, parsePlaylistFile, trackFinder } from "./playlist-file";

const where = { dir: "9/4k", libraryPath: "/music/dj boi" };

describe("parsePlaylistFile", () => {
  test("entries are relative to the playlist's own folder, in order, without comments or blank lines", () => {
    const text = ["# AUTOGENERATED_BY=folder-sync", "# Folder playlist for: 9/4k", "60 Dalek One - 913.mp3", "", "  59 - Simon Says Intro.wav  ", "#EXTINF:12,x", "sub/a.flac"].join("\n");
    expect(parsePlaylistFile(text, where)).toEqual(["9/4k/60 Dalek One - 913.mp3", "9/4k/59 - Simon Says Intro.wav", "9/4k/sub/a.flac"]);
    expect(parsePlaylistFile("a.mp3", { ...where, dir: "" })).toEqual(["a.mp3"]);
  });

  test("a BOM and Windows line endings are not part of a name", () => {
    expect(parsePlaylistFile("\uFEFFa.mp3\r\nb.mp3\r\n", where)).toEqual(["9/4k/a.mp3", "9/4k/b.mp3"]);
    expect(parsePlaylistFile("a.mp3\rb.mp3", where)).toEqual(["9/4k/a.mp3", "9/4k/b.mp3"]);
  });

  test("backslashes, . and .. are worked out", () => {
    expect(parsePlaylistFile("..\\dd\\a.mp3\n./b.mp3\n../../top.mp3", where)).toEqual(["9/dd/a.mp3", "9/4k/b.mp3", "top.mp3"]);
  });

  test("an absolute path is kept when it is inside the library, whatever the case of the library's folder", () => {
    const text = ["/music/dj boi/9/4k/a.mp3", "/Music/DJ Boi/top.mp3", "/music/dj boi 2/b.mp3", "/elsewhere/c.mp3", "/music/dj boi"].join("\n");
    expect(parsePlaylistFile(text, where)).toEqual(["9/4k/a.mp3", "top.mp3"]);
  });

  test("Windows paths work against a Windows library", () => {
    const windows = { dir: "mixes", libraryPath: "C:\\Music" };
    expect(parsePlaylistFile("C:\\Music\\mixes\\a.mp3\nc:/music/b.mp3\nD:\\Music\\c.mp3\nfile:///C:/Music/d%20e.mp3", windows)).toEqual(["mixes/a.mp3", "b.mp3", "d e.mp3"]);
  });

  test("file URLs are decoded, and other addresses are left out", () => {
    const text = ["file:///music/dj%20boi/9/4k/caf%C3%A9.mp3", "file://localhost/music/dj boi/a.mp3", "FILE:///other/b.mp3", "https://radio.test/stream.mp3", "file://nas/music/dj boi/c.mp3"].join("\n");
    expect(parsePlaylistFile(text, where)).toEqual(["9/4k/café.mp3", "a.mp3"]);
  });

  test("an entry that climbs out of the library is left out", () => {
    expect(parsePlaylistFile("../../../a.mp3\n../../b.mp3\n/music/dj boi/../c.mp3", where)).toEqual(["b.mp3"]);
  });

  test("a percent sign in a plain name is left alone", () => {
    expect(parsePlaylistFile("28 Particle - 18% (Original Mix).mp3", where)).toEqual(["9/4k/28 Particle - 18% (Original Mix).mp3"]);
  });
});

describe("decodePlaylistFile", () => {
  test("UTF-8 is read as it is, and anything else as Latin-1", () => {
    expect(decodePlaylistFile(new TextEncoder().encode("café.mp3"))).toBe("café.mp3");
    expect(decodePlaylistFile(Uint8Array.from([0x63, 0x61, 0x66, 0xe9]))).toBe("café");
  });
});

describe("trackFinder", () => {
  const find = trackFinder(
    ["a/Café Del Mar.mp3".normalize("NFD"), "a/one two.mp3", "a/18% (Mix).mp3", "a/x.mp3", "a/X.mp3"].map((relPath, index) => ({ id: index + 1, relPath })),
  );

  test("accents match however they are composed", () => {
    expect(find("a/Café Del Mar.mp3".normalize("NFC"))).toBe(1);
    expect(find("a/Café Del Mar.mp3".normalize("NFD"))).toBe(1);
  });

  test("letter case doesn't matter, but an exact match wins", () => {
    expect(find("A/CAFÉ DEL MAR.MP3")).toBe(1);
    expect(find("a/x.mp3")).toBe(4);
    expect(find("a/X.mp3")).toBe(5);
  });

  test("a percent-encoded plain path is found, and a real percent sign still is", () => {
    expect(find("a/one%20two.mp3")).toBe(2);
    expect(find("a/18% (Mix).mp3")).toBe(3);
  });

  test("an entry with no track finds nothing", () => {
    expect(find("a/gone.mp3")).toBeUndefined();
  });
});
